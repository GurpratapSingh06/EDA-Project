"""
Section 7: Business Intelligence & Interactive Dashboard Systems.
Details the Streamlit BI Web Application architecture (live SQL + CSV fallback),
the 4 functional analytical pages, and the Power BI Developer Project (.pbip) with DAX measures.
"""

from reportlab.platypus import Paragraph, Spacer, PageBreak, KeepTogether, Table, TableStyle
from reportlab.lib import colors
from .config import (
    USABLE_WIDTH, PRIMARY, SECONDARY, ACCENT, DARK_TEXT, LIGHT_BG,
    BORDER_COLOR, make_callout, make_table, make_image_figure, make_concept_card, PageTracker
)

def build_section_7(styles, tracker):
    elements = []
    elements.append(PageTracker('sec7', tracker))
    
    elements.append(Paragraph("<b>Section 7: Business Intelligence & Interactive Dashboard Systems</b>", styles['SectionH1']))
    elements.append(Spacer(1, 4))
    
    elements.append(Paragraph("<b>7.1 The Dual-Engine Dashboard Delivery Architecture</b>", styles['SectionH2']))
    elements.append(Paragraph(
        "To satisfy diverse municipal stakeholders—ranging from tactical officers in patrol cars to data analysts in headquarters—the "
        "project provides two complementary dashboard solutions implementing the certified 4-page analytical architecture:<br/>"
        "• <b>Option A: Interactive Streamlit Web BI Dashboard (Browser-Native):</b> Zero-install Python application running on Streamlit and Plotly.<br/>"
        "• <b>Option B: Microsoft Power BI Developer Project (.pbip):</b> Enterprise BI model containing 6 star schema tables and 8 compiled DAX measures.",
        styles['Body']
    ))
    elements.append(Spacer(1, 6))
    
    # Streamlit Architecture
    elements.append(Paragraph("<b>7.2 Option A: Interactive Streamlit BI Application (dashboard/app.py)</b>", styles['SectionH2']))
    elements.append(Paragraph(
        "The Streamlit BI dashboard implements a resilient dual-engine connection architecture in <code>load_data()</code>:<br/>"
        "1. <b>Primary Live Warehouse Connection:</b> Attempts connection to PostgreSQL 16 on <code>localhost:5432</code> querying <code>mart.PublicSafetyAnalyticsMart</code> with a 3-second timeout.<br/>"
        "2. <b>Resilient CSV Fallback:</b> If PostgreSQL is offline, it automatically intercepts the exception and streams the 497,919 curated records directly from <code>data/curated/crimes_curated.csv</code> in ~2.7 seconds.<br/>"
        "3. <b>In-Memory Caching:</b> Decorated with <code>@st.cache_data</code>, ensuring all cross-page transitions, dynamic slicing, and KPI updates execute in sub-second time.",
        styles['Body']
    ))
    elements.append(Spacer(1, 4))
    
    pbi_pages = [
        ["Dashboard Page", "Analytical Domain", "Key Visual Components & Functional Metrics"],
        ["Page 1: Executive Overview", "Citywide Macro Public Safety Trends", "5 Top KPI Metric Cards (Total Incidents: 497,919, Arrest Rate: 14.94%, Domestic: 18.70%, Night: 30.69%, Distinct Offenses: 31); Dual-axis monthly volume vs arrest clearance line/bar chart; Offense category donut chart; Operational time band bar; Day of week volume chart."],
        ["Page 2: Crime Type Analytics", "Offense Classification & Clearance Disparity", "Top 15 primary statutory offenses horizontal bar; Offense Clearance Scatter Matrix (Incident volume vs arrest clearance % with bubble size mapped to domestic volume); Primary offense clearance summary table."],
        ["Page 3: Geographic Hotspots", "Spatial Distribution Across Police Districts & Areas", "Police district ranking bar chart colored by arrest clearance rate gradient; Premise Environmental Location breakdown donut chart; Top 15 Community Areas summary table (identifying Austin Area 25 as primary hotspot)."],
        ["Page 4: Temporal & Diurnal Heatmap", "Chronological & Diurnal Shift Concentration", "24x7 Day of Week x Hour of Day (0–23) activity concentration matrix heatmap; Comparative diurnal hourly trend line chart contrasting Weekday (Mon–Fri) vs Weekend (Sat–Sun) volume curves."]
    ]
    elements.append(make_table(pbi_pages, col_widths=[110, 125, USABLE_WIDTH - 235], headers=True, styles=styles))
    elements.append(Spacer(1, 10))
    
    # Visual Figures
    elements.append(Paragraph("<b>7.3 Core Visual Analytics Generated by the Platform</b>", styles['SectionH2']))
    elements.extend(make_image_figure('chicago-crime-dw/outputs/figures/fig03_monthly_temporal_trend.png',
                                      "Figure 7.1: Monthly Incident Volume vs. Arrest Clearance Rate demonstrating seasonal summer surge and steady-state 15% clearance.",
                                      width=485, styles=styles))
    elements.extend(make_image_figure('chicago-crime-dw/outputs/figures/fig05_hour_day_heatmap.png',
                                      "Figure 7.2: 24x7 Day of Week by Hour of Day Diurnal Crime Concentration Matrix identifying Friday/Saturday night peak hotspots.",
                                      width=485, styles=styles))
    elements.append(Spacer(1, 8))
    
    # Power BI Section
    elements.append(Paragraph("<b>7.4 Option B: Microsoft Power BI Desktop Developer Project (.pbip)</b>", styles['SectionH2']))
    elements.append(Paragraph(
        "For Microsoft Power BI enterprise environments, a developer project is provided in <code>powerbi/ChicagoCrimeAnalytics.pbip</code>. "
        "The project consists of a report descriptor (<code>definition.pbir</code>) and a semantic model manifest (<code>definition.pbism</code>) "
        "housing a comprehensive Tabular Model Scripting Language (TMSL) file <code>model.bim</code>. "
        "Eight certified DAX measures are embedded directly into the semantic model:",
        styles['Body']
    ))
    elements.append(Spacer(1, 4))
    
    dax_table = [
        ["DAX Measure Name", "Formal DAX Expression", "Analytical Purpose"],
        ["[Total Incidents]", "COUNTROWS(fact_crime_incident_summary)", "Additive measure computing total reported incident volume across all active filters."],
        ["[Total Arrests]", "SUM(fact_crime_incident_summary[Arrests])", "Additive measure aggregating total custodial bookings."],
        ["[Arrest Rate]", "DIVIDE([Total Arrests], [Total Incidents], 0)", "Semi-additive measure computing clearance percentage; handles divide-by-zero safely."],
        ["[Domestic Incidents]", "SUM(fact_crime_incident_summary[Domestic])", "Additive measure summing incidents involving the Illinois Domestic Violence Act."],
        ["[Domestic Rate]", "DIVIDE([Domestic Incidents], [Total Incidents], 0)", "Semi-additive measure calculating domestic violence proportion of total crime."],
        ["[Night Incidents]", "SUM(fact_crime_incident_summary[Night])", "Additive measure quantifying crimes occurring during the Night shift (21:00–04:59)."],
        ["[Night Incident Pct]", "DIVIDE([Night Incidents], [Total Incidents], 0)", "Calculates operational night shift load on municipal patrol resources."],
        ["[Distinct Crime Types]", "DISTINCTCOUNT(fact_crime_incident_summary[CrimeTypeKey])", "Non-additive measure tracking crime diversity across police districts."]
    ]
    elements.append(make_table(dax_table, col_widths=[95, 230, USABLE_WIDTH - 325], headers=True, styles=styles))
    elements.append(Spacer(1, 8))
    
    elements.append(make_callout(
        "<b>Power BI Connection Architecture:</b> The PBIP project can consume data via two distinct pipelines: "
        "(1) Direct SQL Import connecting to PostgreSQL on <code>localhost:5432;chicago_crime_dw</code> querying <code>mart.PublicSafetyAnalyticsMart</code>, "
        "or (2) Flat File Import consuming pre-exported dimensional CSVs in <code>outputs/powerbi_exports/</code>. "
        "When connecting directly to PostgreSQL, ensure 'Encrypt connections' is unchecked in Data Source Settings if SSL is disabled on the local container.",
        title="Power BI Connectivity & Deployment Note", color=PRIMARY, styles=styles
    ))
    
    elements.append(PageBreak())
    return elements
